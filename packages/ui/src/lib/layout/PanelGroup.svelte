let props: Props = $props();

let groupEl: HTMLDivElement | undefined = $state();
let dragging: { index: number; startPos: number; startSizes: number[] } | undefined = $state();

function startResize(event: PointerEvent, index: number): void {
  if (props.node.kind !== 'split') return;
  event.preventDefault();
  dragging = {
    index,
    startPos: props.node.direction === 'row' ? event.clientX : event.clientY,
    startSizes: [...props.node.sizes],
  };
  window.addEventListener('pointermove', onPointerMove);
  window.addEventListener('pointerup', stopResize);
}

function onPointerMove(event: PointerEvent): void {
  if (!dragging || props.node.kind !== 'split' || !groupEl) return;
  const rect = groupEl.getBoundingClientRect();
  const totalSize = props.node.direction === 'row' ? rect.width : rect.height;
  const pos = props.node.direction === 'row' ? event.clientX : event.clientY;
  const deltaPx = pos - dragging.startPos;
  const totalWeight = dragging.startSizes.reduce((a, b) => a + b, 0);
  const deltaWeight = (deltaPx / totalSize) * totalWeight;

  const sizes = [...dragging.startSizes];
  const i = dragging.index;
  const minWeight = totalWeight * 0.08;
  const newLeft = Math.max(minWeight, sizes[i] + deltaWeight);
  // keep the pair's combined weight constant so the rest of the layout doesn't shift, and
  // clamp so neither side shrinks below minWeight
  const pairTotal = sizes[i] + sizes[i + 1];
  const clampedLeft = Math.min(newLeft, pairTotal - minWeight);
  sizes[i] = clampedLeft;
  sizes[i + 1] = pairTotal - clampedLeft;
  props.onResizeSplit(props.node.id, sizes);
}

function stopResize(): void {
  dragging = undefined;
  window.removeEventListener('pointermove', onPointerMove);
  window.removeEventListener('pointerup', stopResize);
}

function equalize(_index: number): void {
  if (props.node.kind !== 'split') return;
  const n = props.node.children.length;
  props.onResizeSplit(
    props.node.id,
    Array.from({ length: n }, () => 100 / n),
  );
}
