let pod = $derived($podsInfos.find(p => p.name === podName && p.engineId === engineId));

$effect(() => {
  if (!pod) return;
  const resourceId = podKey(pod.name, pod.engineId);
  if (!findAnyTabForResource('pod', resourceId)) {
