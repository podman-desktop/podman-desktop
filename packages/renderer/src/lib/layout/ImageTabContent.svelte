  <div class="flex flex-col h-full min-h-0">
    <div class="grow min-h-0 overflow-auto">
      {#if subView === 'history'}
        <ImageDetailsHistory image={image} />
      {:else if subView === 'inspect'}
        <ImageDetailsInspect image={image} />
      {:else}
        <ImageDetailsSummary image={image} />
      {/if}
    </div>
  </div>
{:else}
  <StaleTabPlaceholder resourceLabel="Image" tabId={tabId} />
{/if}
