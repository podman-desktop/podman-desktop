import type { ViewInfoUI } from '@podman-desktop/core-api';

import { ImageUtils } from '/@/lib/image/image-utils';
import ImageDetailsHistory from '/@/lib/image/ImageDetailsHistory.svelte';
import ImageDetailsInspect from '/@/lib/image/ImageDetailsInspect.svelte';
import ImageDetailsSummary from '/@/lib/image/ImageDetailsSummary.svelte';
import {
  IMAGE_DETAILS_VIEW_BADGES,
  IMAGE_DETAILS_VIEW_ICONS,
  IMAGE_VIEW_BADGES,
  IMAGE_VIEW_ICONS,
} from '/@/lib/view/views';
import { containersInfos } from '/@/stores/containers';
import { context } from '/@/stores/context';
import { imagesInfos } from '/@/stores/images';
import { markTabStale } from '/@/stores/layout/layout-store.svelte';
import type { ImageSubView } from '/@/stores/layout/layout-types';
import { viewsContributions } from '/@/stores/views';

import StaleTabPlaceholder from './StaleTabPlaceholder.svelte';

interface Props {
  tabId: string;
  imageId: string;
  engineId: string;
  base64RepoTag: string;
  subView?: ImageSubView;
}

let { tabId, imageId, engineId, base64RepoTag, subView = 'summary' }: Props = $props();

const imageUtils = new ImageUtils();

let viewContributions: ViewInfoUI[] = $derived(
  $viewsContributions.filter(
    view =>
      view.viewId === IMAGE_DETAILS_VIEW_ICONS ||
      view.viewId === IMAGE_VIEW_ICONS ||
      view.viewId === IMAGE_VIEW_BADGES ||
      view.viewId === IMAGE_DETAILS_VIEW_BADGES,
  ),
);

let imageInfo = $derived($imagesInfos.find(c => c.Id === imageId && c.engineId === engineId));
let image = $derived.by(() =>
  imageInfo
    ? imageUtils.getImageInfoUI(imageInfo, base64RepoTag, $containersInfos, $context, viewContributions)
    : undefined,
);

$effect(() => {
  markTabStale(tabId, !image);
});
