import ContainerDetailsTtyTerminal from '/@/lib/container/ContainerDetailsTtyTerminal.svelte';
import { containersInfos } from '/@/stores/containers';
import { markTabStale } from '/@/stores/layout/layout-store.svelte';
import type { ContainerSubView } from '/@/stores/layout/layout-types';

import StaleTabPlaceholder from './StaleTabPlaceholder.svelte';

interface Props {
  tabId: string;
  containerId: string;
  subView?: ContainerSubView;
}

let { tabId, containerId, subView = 'summary' }: Props = $props();

const containerUtils = new ContainerUtils();

let container = $derived.by(() => {
  const found = $containersInfos.find(c => c.Id === containerId);
  return found ? containerUtils.getContainerInfoUI(found) : undefined;
});

$effect(() => {
  markTabStale(tabId, !container);
});
