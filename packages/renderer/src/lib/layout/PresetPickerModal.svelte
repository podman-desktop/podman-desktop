// Minimal resource pickers for the four built-in presets (section 4.8).
import { Button } from '@podman-desktop/ui-svelte';
import { router } from 'tinro';

import { ContainerUtils } from '/@/lib/container/container-utils';
import Dialog from '/@/lib/dialogs/Dialog.svelte';
import { ImageUtils } from '/@/lib/image/image-utils';
import { containersInfos } from '/@/stores/containers';
import { imagesInfos } from '/@/stores/images';
import {
  applyDebugDuoPreset,
  applyImageDiffPreset,
  applyLogsPlusTerminalPreset,
  applyPodInspectorPreset,
  type PresetId,
} from '/@/stores/layout/layout-presets';
import { podsInfos } from '/@/stores/pods';

interface Props {
  presetId: PresetId;
  onClose: () => void;
}

let { presetId, onClose }: Props = $props();

const containerUtils = new ContainerUtils();
const imageUtils = new ImageUtils();

const containerOptions = $derived($containersInfos.map(c => containerUtils.getContainerInfoUI(c)));
const podOptions = $derived($podsInfos);
const imageOptions = $derived(
  $imagesInfos.flatMap(i => imageUtils.getImagesInfoUI(i, $containersInfos, undefined, [], $imagesInfos)),
);

let containerAId = $state('');
let containerBId = $state('');
let podResourceId = $state('');
let imageAId = $state('');
let imageBId = $state('');

const canApply = $derived.by(() => {
  switch (presetId) {
    case 'debug-duo':
      return !!containerAId && !!containerBId && containerAId !== containerBId;
    case 'logs-terminal':
      return !!containerAId;
    case 'pod-inspector':
      return !!podResourceId;
    case 'image-diff':
      return !!imageAId && !!imageBId && imageAId !== imageBId;
    default:
      return false;
  }
});

function apply(): void {
  switch (presetId) {
    case 'debug-duo': {
      const a = containerOptions.find(c => c?.id === containerAId);
      const b = containerOptions.find(c => c?.id === containerBId);
      if (a && b) applyDebugDuoPreset(a, b);
      break;
    }
    case 'logs-terminal': {
      const a = containerOptions.find(c => c?.id === containerAId);
      if (a) applyLogsPlusTerminalPreset(a);
      break;
    }
    case 'pod-inspector': {
      const pod = podOptions.find(p => p.id === podResourceId);
      if (pod) {
        const firstContainer = pod.containers[0];
        applyPodInspectorPreset(
          pod,
          firstContainer ? { id: firstContainer.Id, name: firstContainer.Names } : undefined,
        );
      }
      break;
    }
    case 'image-diff': {
      const a = imageOptions.find(i => i?.id === imageAId);
      const b = imageOptions.find(i => i?.id === imageBId);
      if (a && b) applyImageDiffPreset(a, b);
      break;
    }
  }
  // The Layout menu is global chrome (see App.svelte), so applying a preset from any page
  // needs to jump to /workspace for the user to actually see the panels it created.
  router.goto('/workspace');
  onClose();
}

const titles: Record<PresetId, string> = {
  'debug-duo': 'Debug Duo',
  'logs-terminal': 'Logs + Terminal',
  'pod-inspector': 'Pod Inspector',
  'image-diff': 'Image Diff',
};
